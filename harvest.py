#Assignment Operators
field1 = 10
field2 = 20
field3 = 30

#Arithmetic Operators
total = field1 + field2 + field3
average = total / 3 #division operator
print("Total:", total)
print("Average:", average)

price_per_kg = 5
income = price_per_kg * total #multiplication operator
print("Income:", income)

#Comparison Operators
last_year = 50
print("Is this year's total greater than last year's?", total > last_year) #greater than operator